import { test, expect, type Page } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';

async function technicalPoint(page: Page, coordinates: [number, number]) {
  await page.getByText('Szczegóły punktu: współrzędne', { exact: true }).click();
  await page.getByLabel('Szerokość geograficzna', { exact: true }).fill(String(coordinates[1]));
  await page.getByLabel('Długość geograficzna', { exact: true }).fill(String(coordinates[0]));
  await page.getByRole('button', { name: 'Ustaw punkt ze współrzędnych', exact: true }).click();
  await page.getByRole('button', { name: 'To miejsce obserwacji', exact: true }).click();
}

test('training grows the garden, buys decorations once and never writes observations', async ({ page }) => {
  const writes: string[] = [];
  const errors: string[] = [];
  page.on('request', request => { if (request.method() === 'POST' && request.url().includes('/api/')) writes.push(request.url()); });
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/gra?tryb=ogrod');
  await expect(page).toHaveTitle('Iskry Miasta · Twój mały ogród');
  await expect(page.locator('link[rel="manifest"]')).toHaveAttribute('href', '/iskry.webmanifest');
  const manifest = await (await page.request.get('/iskry.webmanifest')).json();
  expect(manifest.start_url).toBe('/gra'); expect(manifest.id).toBe('/gra');
  await page.getByRole('button', { name: 'Zatrzymaj animacje ogrodu' }).click();
  await expect(page.locator('.ig-bird > svg')).toHaveCSS('animation-play-state', 'paused');
  await page.getByRole('button', { name: 'Zacznij małe odkrycie' }).click();
  await expect(page.getByRole('heading', { name: 'Brama z niespodzianką' })).toBeFocused();
  await page.getByRole('button', { name: /Szerokie drzwi wystarczą/ }).click();
  await expect(page.getByRole('status')).toContainText('Spójrz na dolną krawędź drzwi');
  await expect(page.locator('.ig-garden-stats')).toContainText('0 iskier');
  await page.getByRole('button', { name: /Przed wejściem jest stopień/ }).click();
  await expect(page.getByRole('heading', { name: 'Pierwsze pędy' })).toBeVisible();
  await expect(page.locator('.ig-garden-gift')).toContainText('+20 iskier');
  await expect(page.locator('.ig-garden-gift')).toHaveCSS('opacity', '1');
  await expect(page.locator('.ig-world .ig-sprout-in').first()).toHaveCSS('animation-name', 'none');
  await page.getByRole('button', { name: 'Łąka iskier, 15 iskier, grządka 1', exact: true }).click();
  await expect(page.locator('.ig-garden-stats')).toContainText('5 iskier');
  await expect(page.getByRole('button', { name: 'Grządka 1, z ozdobą' })).toBeVisible();
  await page.getByRole('button', { name: 'Grządka 3, pusta' }).click();
  await page.getByRole('button', { name: 'Łąka iskier, odblokowana, ustaw bez kosztu, grządka 3' }).click();
  await expect(page.getByRole('button', { name: 'Grządka 3, z ozdobą' })).toBeVisible();
  await expect(page.locator('.ig-garden-stats')).toContainText('5 iskier');
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([]);
  await page.reload();
  await expect(page.getByRole('button', { name: /01 Brama z niespodzianką|Brama z niespodzianką.*Gotowe/ })).toBeDisabled();
  await expect(page.getByRole('button', { name: 'Grządka 3, z ozdobą' })).toBeVisible();
  await page.getByRole('button', { name: /02 Miara ma znaczenie/ }).click();
  await page.getByRole('button', { name: /86 cm wolnego przejścia/ }).click();
  await expect(page.getByRole('heading', { name: 'Zielona przystań' })).toBeVisible();
  expect(writes).toEqual([]); expect(errors).toEqual([]);
});

