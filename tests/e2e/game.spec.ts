test('city observation uses the signed in account and server reward, then persists its decoration', async ({ page }) => {
  const registration = await page.request.post('/api/auth/register', { data: { email: `game-${Date.now()}@example.invalid`, password: 'Synthetic-local-test-2026!', displayName: 'Tester ogrodu' } });
  expect(registration.status()).toBe(201);
  const account = await (await page.request.get('/api/auth/me')).json();
  await page.goto('/gra?tryb=ogrod');
  await page.getByRole('button', { name: 'Moje miasto', exact: true }).click();
  await page.getByRole('button', { name: /Wypatrz przewężenie/ }).first().click();
  const list = await (await page.request.get('/api/game/missions')).json();
  const mission = list.missions.find((item: { kind: string }) => item.kind === 'width');
  await technicalPoint(page, mission.target.coordinates);
  await page.getByLabel('Zmierzona wolna szerokość w cm').fill('85');
  await page.getByLabel('Co dokładnie zauważono?').fill('Syntetyczna obserwacja wyłącznie w izolowanej bazie testowej między słupkiem a ścianą budynku.');
  await page.getByRole('checkbox').check();
  const reportResponse = page.waitForResponse(response => response.url().endsWith('/api/reports') && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Zapisz obserwację i odbierz iskry' }).click();
  const report = await (await reportResponse).json();
  await expect(page.locator('.ig-garden-gift')).toContainText('+20 iskier');
  expect(report.isMine).toBe(true); expect(report.userId).toBeUndefined();
  const decorationResponse = page.waitForResponse(response => response.url().endsWith('/api/game/decorate') && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Łąka iskier, 15 iskier, grządka 1', exact: true }).click();
  expect((await decorationResponse).status()).toBe(200);
  await expect(page.locator('.ig-garden-stats')).toContainText('5 iskier');
  const state = await (await page.request.get('/api/game/state')).json();
  expect(state.earned).toBe(20); expect(state.spent).toBe(15); expect(state.observations).toBe(1);
  expect(state.decorations).toEqual([{ slot: 0, itemId: 'flowers' }]);
  const replay = await page.request.post('/api/game/claim', { data: { reportId: report.id, missionId: mission.id, expectedUserId: account.user.id } });
  expect((await replay.json()).awarded).toBe(0);
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([]);
});

