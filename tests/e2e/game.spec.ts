test('positive city discovery is public separately, earns once and can be withdrawn without a barrier', async ({ page }) => {
  const registration = await page.request.post('/api/auth/register', { data: { email: `good-discovery-${Date.now()}@example.invalid`, password: 'Synthetic-local-test-2026!', displayName: 'Tester dobrych miejsc' } });
  expect(registration.status()).toBe(201);
  const before = await (await page.request.get('/api/reports')).json();
  const writes: string[] = [];
  page.on('request', request => { if (request.method() === 'POST') writes.push(new URL(request.url()).pathname); });
  await page.addInitScript(() => {
    Object.defineProperty(navigator, 'geolocation', { configurable: true, value: { getCurrentPosition: (callback: PositionCallback) => { (window as unknown as { delayedGameGPS: PositionCallback }).delayedGameGPS = callback; } } });
  });
  await page.goto('/gra?tryb=ogrod');
  await page.getByRole('button', { name: 'Moje miasto', exact: true }).click();
  await page.getByRole('button', { name: 'Dobre odkrycia', exact: true }).click();
  await expect(page.getByRole('button', { name: /Wypatrz przewężenie/ })).toHaveCount(0);
  await page.getByRole('button', { name: /Odkryj przystanek odpoczynku/ }).first().click();
  await expect(page.getByText('Osobne dobre odkrycie.', { exact: true })).toBeVisible();
  const list = await (await page.request.get('/api/game/missions')).json();
  const mission = list.missions.find((item: { kind: string }) => item.kind === 'rest_place');
  await expect(page.getByRole('button', { name: 'To miejsce obserwacji', exact: true })).toBeDisabled();
  await page.getByRole('combobox', { name: 'Adres w okolicy obserwacji' }).fill('Rynek Główny 1');
  await page.getByRole('listbox', { name: 'Podpowiedzi: Adres w okolicy obserwacji' }).getByRole('option', { name: /Rynek Główny 1, Kraków/ }).first().click();
  await expect(page.getByRole('button', { name: 'To miejsce obserwacji', exact: true })).toBeEnabled();
  await expect(page.getByRole('button', { name: 'Zapisz obserwację i odbierz iskry' })).toBeDisabled();
  await page.getByRole('button', { name: 'Użyj mojego GPS', exact: true }).click();
  await page.getByRole('button', { name: 'Wróć do misji', exact: true }).click();
  await page.getByRole('button', { name: /Odkryj przystanek odpoczynku/ }).first().click();
  await page.evaluate(() => (window as unknown as { delayedGameGPS: PositionCallback }).delayedGameGPS({ coords: { longitude: 20.11, latitude: 50.12, accuracy: 5 } } as GeolocationPosition));
  await expect(page.getByRole('button', { name: 'To miejsce obserwacji', exact: true })).toBeDisabled();
  await expect(page.getByRole('button', { name: 'Ustaw pinezkę w środku mapy', exact: true })).toBeEnabled();
  const mapCanvas = page.getByRole('region', { name: 'Mapa punktu obserwacji', exact: true }).locator('canvas');
  const mapBox = await mapCanvas.boundingBox(); expect(mapBox).not.toBeNull();
  await mapCanvas.click({ position: { x: mapBox!.width * .65, y: mapBox!.height * .45 } });
  const selectedPoint = [Number(await page.getByLabel('Długość geograficzna', { exact: true }).inputValue()), Number(await page.getByLabel('Szerokość geograficzna', { exact: true }).inputValue())];
  expect(Math.abs(selectedPoint[0] - mission.target.coordinates[0]) + Math.abs(selectedPoint[1] - mission.target.coordinates[1])).toBeGreaterThan(.000001);
  await expect(page.getByRole('button', { name: 'Zapisz obserwację i odbierz iskry' })).toBeDisabled();
  await page.getByRole('button', { name: 'To miejsce obserwacji', exact: true }).click();
  await page.getByLabel('Co dokładnie zauważono?').fill('Syntetyczna ławka z oparciem przy północnej alejce, wyłącznie w izolowanej bazie testowej.');
  await page.getByRole('checkbox').check();
  const response = page.waitForResponse(value => value.url().endsWith('/api/observations') && value.request().method() === 'POST');
  await page.getByRole('button', { name: 'Zapisz obserwację i odbierz iskry' }).click();
  const observation = await (await response).json();
  expect(observation.coordinates).toEqual(selectedPoint);
  await expect(page.locator('.ig-garden-gift')).toContainText('+15 iskier');
  expect(observation.verification).toBe('unverified'); expect(observation.affectsRouting).toBe(false);
  expect((await (await page.request.get('/api/reports')).json()).reports.length).toBe(before.reports.length);
  const publicItems = await (await page.request.get('/api/observations')).json();
  expect(publicItems.observations.some((item: { id: string }) => item.id === observation.id)).toBe(true);
  await page.getByRole('button', { name: 'Moje odkrycia', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Moje dobre odkrycia' })).toBeVisible();
  await expect(page.getByText('Publiczna obserwacja', { exact: true })).toBeVisible();
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([]);
  await page.getByRole('button', { name: 'Wycofaj odkrycie', exact: true }).click();
  await expect(page.getByText('Wycofane', { exact: true })).toBeVisible();
  const after = await (await page.request.get('/api/observations')).json();
  expect(after.observations.some((item: { id: string }) => item.id === observation.id)).toBe(false);
  expect((await (await page.request.get('/api/game/state')).json()).earned).toBe(15);
  expect(writes).not.toContain('/api/reports');
});
